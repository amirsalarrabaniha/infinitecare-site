#!/usr/bin/env python3
"""Regenerate the '*.html -> clean URL' block of _redirects (Cloudflare) from the exported pages.
Cloudflare's html_handling would answer /services.html with a 307; these explicit rules make it a single 301.
Usage: scripts/html_redirects.py <site root>"""
import os, sys
root = sys.argv[1] if len(sys.argv) > 1 else '.'
BEGIN, END = '# BEGIN html->clean (generated by scripts/html_redirects.py)', '# END html->clean'
path = os.path.join(root, '_redirects')
lines = open(path, encoding='utf-8').read().split('\n')
if BEGIN in lines:
    lines = lines[:lines.index(BEGIN)] + lines[lines.index(END) + 1:]
while lines and not lines[-1].strip():
    lines.pop()
taken = {l.split()[0] for l in lines if l.strip() and not l.startswith('#')}
rules = []
for d in ['', 'hu', 'blog', 'hu/blog']:
    full = os.path.join(root, d)
    if not os.path.isdir(full):
        continue
    for f in sorted(os.listdir(full)):
        if not f.endswith('.html'):
            continue
        src = '/' + (d + '/' if d else '') + f
        dst = '/' + (d + '/' if d else '') + ('' if f == 'index.html' else f[:-5])
        if src not in taken:
            rules.append(f'{src} {dst} 301')
open(path, 'w', encoding='utf-8').write('\n'.join(lines + ['', BEGIN] + rules + [END, '']))
